export function buildAnswers({ profile, truthIndex, job, cvSkillIds }) {
  const questions = [];
  // Questions can arrive from the source connector (requirements.questions), from a
  // manual/copied advert, or from a guided connector's handoff — all three are accepted.
  const explicit = job.requirements?.questions || job.questions || job.apply?.questions || [];
  for (const q of explicit) questions.push({ question: String(q.question || q), required: q.required !== false });
  // Fall back to questions phrased inside the advert text.
  if (!questions.length) {
    const text = job.description || '';
    const candidates = text.match(/[^?\n]{12,160}\?/g) || [];
    for (const c of candidates.slice(0, 8)) {
      if (/(you|your|do you|have you|are you|can you|will you)/i.test(c)) questions.push({ question: c.trim(), required: false });
    }
  }

  const answers = questions.slice(0, 10).map((q) => {
    const rule = QUESTION_RULES.find((r) => r.test.test(q.question));
    if (!rule) {
      return {
        question: q.question,
        answer: '',
        source: 'missing',
        needsUser: true,
        autoGenerated: false,
        note: 'Not answerable from the CV — answer this yourself.',
      };
    }
    const built = rule.build({ profile, truthIndex, cvSkillIds, job, match: rule.test.exec(q.question) || [] });
    return {
      question: q.question,
      answer: built.answer,
      source: built.source,
      needsUser: !!built.needsUser,
      note: built.note || null,
      autoGenerated: !!built.answer,
      rule: rule.id,
    };
  });

  // Always give the user the standing answers they may need.
  if (!answers.some((a) => a.rule === 'salary') && profile.salaryExpectation) {
    answers.push({ question: 'Salary expectation (if asked)', answer: `My expectation is ${profile.salaryExpectation}.`, source: 'cv', needsUser: false, autoGenerated: true, rule: 'salary' });
  }
  if (!answers.some((a) => a.rule === 'notice_period') && profile.noticePeriod) {
    answers.push({ question: 'Notice period (if asked)', answer: `My notice period is ${profile.noticePeriod.replace(/^notice period[:\s]*/i, '')}.`, source: 'cv', needsUser: false, autoGenerated: true, rule: 'notice_period' });
  }
  for (const a of answers) repairBoolean(a);
  return answers;
}

function repairBoolean(a) {
  if (typeof a.autoGenerated === 'string') a.autoGenerated = a.autoGenerated === 'true';
  return a;
}

function describeFocus(job) {
  const skills = extractSkills(`${job.title}\n${job.description || ''}`, { limit: 3 }).map((s) => s.label);
  if (skills.length) return listPhrase(skills.map((s) => s.toLowerCase()));
  return 'building products that solve real user problems';
}

/* ------------------------------------------------------------------ *
 * Helpers
 * ------------------------------------------------------------------ */

function guard(text, truthIndex, label, allow = []) {
  const result = validate(text, truthIndex, { allow });
  if (!result.ok) log.warn(`truth guard flagged ${label}`, { violations: result.violations.map((v) => v.type) });
  return result;
}

function orderByRelevance(skills, jobSkillIds) {
  const wanted = new Set(jobSkillIds);
  return [...skills].sort((a, b) => {
    const aScore = (wanted.has(a.id) ? 10 : 0) + (a.hits || 0) + (a.category === 'tool' ? 0.5 : 0);
    const bScore = (wanted.has(b.id) ? 10 : 0) + (b.hits || 0) + (b.category === 'tool' ? 0.5 : 0);
    return bScore - aScore;
  });
}

function rankExperience(experience, jobSkillIds) {
  const wanted = new Set(jobSkillIds);
  return experience.map((e, index) => {
    const text = extractSkills(`${e.title} ${(e.highlights || []).join(' ')} ${e.description || ''}`, { limit: 20 });
    const relevance = text.filter((s) => wanted.has(s.id)).length;
    return { ...e, relevance, recencyIndex: index };
  }).sort((a, b) => {
    if (a.current !== b.current) return a.current ? -1 : 1;
    if (b.relevance !== a.relevance) return b.relevance - a.relevance;
    return a.recencyIndex - b.recencyIndex;
  });
}

function rankProjects(projects, jobSkillIds) {
  const wanted = new Set(jobSkillIds);
  return projects.map((p) => ({
    ...p,
    relevance: extractSkills(`${p.name} ${p.description || ''}`, { limit: 10 }).filter((s) => wanted.has(s.id)).length,
  })).sort((a, b) => b.relevance - a.relevance);
}

function rankAchievements(achievements, jobSkillIds) {
  const wanted = new Set(jobSkillIds);
  const normalised = achievements.map((a) => (typeof a === 'string' ? { text: a, quantified: /\d/.test(a) } : a));
  return normalised
    .map((a) => ({ ...a, relevance: extractSkills(a.text, { limit: 8 }).filter((s) => wanted.has(s.id)).length }))
    .sort((a, b) => b.relevance - a.relevance || Number(b.quantified) - Number(a.quantified));
}

function latestDescriptionSentence(experience) {
  const highlight = (experience.highlights || [])[0];
  if (highlight) return `I ${lowerFirst(highlight.replace(/\.$/, ''))}.`;
  if (experience.description) return firstSentences(experience.description, 1);
  return `I worked across ${listPhrase(extractSkills(`${experience.title}`, { limit: 3 }).map((s) => s.label.toLowerCase())) || 'the full product lifecycle'}.`;
}

function firstSentences(text = '', count = 1) {
  const parts = String(text).split(/(?<=[.!?])\s+/).filter(Boolean);
  return parts.slice(0, count).join(' ');
}

/** True when two bullets say substantially the same thing. */
function overlaps(a = '', b = '') {
  const na = normaliseText(a);
  const nb = normaliseText(b);
  if (!na || !nb) return false;
  if (na.includes(nb) || nb.includes(na)) return true;
  const wordsA = new Set(na.split(' ').filter((w) => w.length > 3));
  const wordsB = nb.split(' ').filter((w) => w.length > 3);
  if (!wordsA.size || !wordsB.length) return false;
  const shared = wordsB.filter((w) => wordsA.has(w)).length;
  return shared / Math.max(wordsA.size, wordsB.length) > 0.5;
}

function dedupeSentences(sentences) {
  const seen = new Set();
  return sentences.filter((s) => {
    const key = normaliseText(s).slice(0, 60);
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function listPhrase(items = []) {
  const clean = items.filter(Boolean);
  if (!clean.length) return '';
  if (clean.length === 1) return clean[0];
  if (clean.length === 2) return `${clean[0]} and ${clean[1]}`;
  return `${clean.slice(0, -1).join(', ')} and ${clean[clean.length - 1]}`;
}

function formatYears(value) {
  const n = Number(value);
  if (!Number.isFinite(n)) return '';
  if (n >= 1) return String(Math.floor(n * 10) / 10).replace(/\.0$/, '');
  return String(Math.max(0.5, Math.round(n * 10) / 10));
}

function article(word = '') {
  return `${/^[aeiou]/i.test(word) ? 'an' : 'a'} ${word}`;
}

function lowerFirst(s = '') {
  return s ? s.charAt(0).toLowerCase() + s.slice(1) : s;
}

const ACRONYMS = /\b[A-Z]{2,}\b/;
const PROPER_TOOLS = /\b(Figma|Sketch|React|Vue|Angular|Svelte|Python|Java|JavaScript|TypeScript|Photoshop|Illustrator|InDesign|After Effects|Miro|Storybook|Tailwind|Bootstrap|Webflow|Canva|Zeplin|Framer|WordPress|Shopify|Jira|Confluence|Notion|Luno|Google|Adobe|Figma|Dovetail|Maze|Hotjar)\b/;

/**
 * Lower-cases a title-cased phrase for mid-sentence use without mangling acronyms
 * ("Motion & Animation" -> "motion & animation", "UX Research" stays "UX Research").
 */
function softLower(phrase = '') {
  const value = String(phrase);
  if (ACRONYMS.test(value) || PROPER_TOOLS.test(value)) return value;
  if (/^([A-Z][a-z']+(?: &)?\s?)+[A-Z][a-z']+$/.test(value)) return value.toLowerCase();
  return lowerFirst(value);
}

