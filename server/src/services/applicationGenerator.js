function composeSummary({ profile, job, role, jobSkills, relevantSkills }) {
  const name = profile.fullName?.split(' ')[0] || 'I';
  const seniority = role?.label || profile.headline || profile.jobTitles?.[0] || 'design professional';
  const years = profile.yearsExperience;
  const yearsPhrase = years ? `${formatYears(years)} years' experience` : 'hands-on experience';
  const topSkills = relevantSkills.slice(0, 5).map((s) => s.label || s);
  const industries = (profile.industries || []).slice(0, 2);
  const achievement = (profile.achievements || []).find((a) => typeof a === 'object' && a.quantified)?.text;

  const sentences = [
    `${seniority} with ${yearsPhrase} across ${industries.length ? industries.join(' and ') : 'digital product teams'}.`,
    topSkills.length ? `Core strengths: ${listPhrase(topSkills)}.` : null,
  ].filter(Boolean);

  // The CV's own summary line is kept only when it adds something new.
  const cvSummaryLine = profile.summary ? firstSentences(profile.summary, 1) : null;
  if (cvSummaryLine && !overlaps(cvSummaryLine, sentences[0] || '')) sentences.push(cvSummaryLine);
  if (achievement) sentences.push(`Recent impact: ${achievement.replace(/\.$/, '')}.`);

  return dedupeSentences(sentences).join(' ').slice(0, 700);
}

function composeCoverLetter({ profile, job, match, settings, relevantSkills, achievements, role }) {
  const greeting = 'Dear Hiring Manager,';
  const firstName = profile.fullName?.split(' ')[0] || '';
  const roleLabel = role?.label || job.title;
  const company = job.company || 'your team';
  const years = profile.yearsExperience;
  const yearsPhrase = years ? `${formatYears(years)} years` : 'several years';
  const strong = (match?.strongMatches || []).slice(0, 5);
  const gaps = (match?.gaps || []).slice(0, 2);
  const topAchievement = achievements.find((a) => a.quantified)?.text || achievements[0]?.text;
  // Never repeat the same result twice in one letter (many CVs restate achievements
  // in both the summary and the role bullets).
  const secondAchievement = achievements.find((a) => a.quantified && a.text !== topAchievement && !overlaps(a.text, topAchievement))?.text;

  const p1 =
    `I'm applying for the ${job.title} role at ${company}. ` +
    `I'm a ${roleLabel} with ${yearsPhrase} of experience` +
    `${profile.industries?.length ? ` in ${listPhrase(profile.industries.slice(0, 2))}` : ''}, and the requirements in your advert line up closely with the work I do day to day.`;

  const p2Parts = [];
  if (strong.length) p2Parts.push(`The areas that overlap most directly are ${listPhrase(strong)}.`);
  const extraSkills = relevantSkills.filter((skill) => !strong.some((s) => s.toLowerCase() === String(skill).toLowerCase())).slice(0, 4);
  if (extraSkills.length) p2Parts.push(`I also work regularly in ${listPhrase(extraSkills)}.`);
  if (profile.experience?.[0]?.title && profile.experience?.[0]?.company) {
    const latest = profile.experience[0];
    p2Parts.push(`Most recently, as ${article(latest.title)} at ${latest.company}, ${latestDescriptionSentence(latest)}`);
  }
  const p2 = p2Parts.join(' ');

  const p3Parts = [];
  if (topAchievement) p3Parts.push(`A result I'm proud of: ${lowerFirst(topAchievement.replace(/\.$/, ''))}.`);
  if (secondAchievement) p3Parts.push(`I also ${lowerFirst(secondAchievement.replace(/\.$/, ''))}.`);
  if (!p3Parts.length && profile.projects?.length) {
    const project = profile.projects[0];
    p3Parts.push(`I recently worked on ${project.name}${project.description ? ` — ${lowerFirst(project.description.slice(0, 180))}` : ''}.`);
  }
  const p3 = p3Parts.join(' ');

  const p4 = gaps.length
    ? `If it's useful, I'd be glad to talk through where I'd ramp up quickly — ${listPhrase(gaps.map(softLower))} ${
        gaps.length === 1 ? 'is an area' : 'are areas'
      } I'd approach with a structured plan.`
    : `I'd welcome the chance to talk through how I can help ${company} with this work.`;

  const availability = [
    profile.noticePeriod ? `I can start ${/immediately/i.test(profile.noticePeriod) ? 'immediately' : `after ${profile.noticePeriod.replace(/^notice period[:\s]*/i, '')}`}.` : null,
    profile.workAuthorization ? `Work authorisation: ${profile.workAuthorization}.` : null,
  ].filter(Boolean);

  const closing = availability.length
    ? availability.join(' ')
    : 'I can make myself available for an interview at short notice.';

  const signoff = ['Kind regards,', profile.fullName || firstName || '', profile.phone, profile.email, profile.portfolioUrl, profile.linkedinUrl]
    .filter(Boolean)
    .join('\n');

  return [greeting, p1, p2, p3, p4, closing, signoff].filter((s) => s && s.trim()).join('\n\n');
}

function composeIntro({ profile, job, relevantSkills, achievements }) {
  const roleLabel = profile.headline || profile.jobTitles?.[0] || 'Designer';
  const years = profile.yearsExperience;
  const yearsPhrase = years ? `${formatYears(years)} years' experience` : 'hands-on experience';
  const top = achievements.find((a) => a.quantified)?.text;
  return [
    `${roleLabel} with ${yearsPhrase}${profile.industries?.length ? ` in ${listPhrase(profile.industries.slice(0, 2))}` : ''}.`,
    relevantSkills.length ? `Focused on ${listPhrase(relevantSkills.slice(0, 5))}.` : '',
    job.title ? `Applying for ${job.title}${job.company ? ` at ${job.company}` : ''}.` : '',
    top ? `Recent highlight: ${top.replace(/\.$/, '')}.` : '',
  ]
    .filter(Boolean)
    .join(' ')
    .slice(0, 500);
}

