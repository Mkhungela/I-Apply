/**
 * Application generation.
 *
 * Builds a job-specific application package using ONLY facts from the CV:
 * tailored CV content, cover letter, short introduction, and answers to the
 * questions the advert asks. Any question that cannot be answered truthfully from
 * the CV is marked `needsUser` — the application then waits for the user instead of
 * guessing. Generated prose is validated by the truth guard.
 */
import { validate } from './truthGuard.js';
import { extractSkills, normaliseText, SKILL_BY_ID, resolveRole } from './skillTaxonomy.js';
import { complete, available as llmAvailable } from './llm.js';
import { logger } from '../lib/logger.js';

const log = logger('generator');

export function generateApplication({ profile, truthIndex, job, match, settings = {}, userId = null }) {
  const role = resolveRole(job.title) || resolveRole((settings.roles || [])[0]);
  const jobSkills = extractSkills(`${job.title}\n${job.description || ''}`, { limit: 40 }).map((s) => s.id);
  const cvSkillIds = new Set((truthIndex.skillIds || []).map(String));

  const relevantSkills = orderByRelevance(profile.skills || [], jobSkills);
  const relevantTools = orderByRelevance(
    (profile.skills || []).filter((s) => s.category === 'tool'),
    jobSkills
  );
  const relevantExperience = rankExperience(profile.experience || [], jobSkills);
  const relevantProjects = rankProjects(profile.projects || [], jobSkills);
  const relevantAchievements = rankAchievements(profile.achievements || [], jobSkills);

  const tailoredCv = {
    header: {
      name: profile.fullName,
      headline: profile.headline,
      email: profile.email,
      phone: profile.phone,
      location: profile.location,
      linkedin: profile.linkedinUrl,
      portfolio: profile.portfolioUrl,
      github: profile.githubUrl,
    },
    target: { title: job.title, company: job.company },
    summary: composeSummary({ profile, job, role, jobSkills, relevantSkills }),
    coreSkills: relevantSkills.slice(0, 14).map((s) => s.label || s),
    tools: relevantTools.slice(0, 10).map((s) => s.label || s),
    experience: relevantExperience.map((e) => ({
      title: e.title,
      company: e.company,
      location: e.location,
      startDate: e.startDate,
      endDate: e.endDate,
      current: e.current,
      highlights: e.highlights.slice(0, 4),
      description: e.description,
    })),
    education: profile.education || [],
    certifications: profile.certifications || [],
    projects: relevantProjects.slice(0, 3),
    languages: profile.languages || [],
    yearsExperience: profile.yearsExperience,
  };

  const coverLetter = composeCoverLetter({
    profile,
    job,
    match,
    settings,
    relevantSkills: tailoredCv.coreSkills,
    achievements: relevantAchievements,
    role,
  });

  const intro = composeIntro({ profile, job, relevantSkills: tailoredCv.coreSkills, achievements: relevantAchievements });

  const answers = buildAnswers({ profile, truthIndex, job, settings, cvSkillIds });

  // Truth guard on every generated string.
  // The target employer and role are legitimate to name; nothing else is added.
  const allow = [job.company, job.title, ...(job.company ? String(job.company).split(/\s+/) : [])].filter(Boolean);
  const guarded = {
    coverLetter: guard(coverLetter, truthIndex, 'cover letter', allow),
    intro: guard(intro, truthIndex, 'introduction', allow),
    summary: guard(tailoredCv.summary, truthIndex, 'CV summary', allow),
    answers: answers.map((a) => (a.autoGenerated ? { ...a, answer: guard(a.answer, truthIndex, `answer: ${a.question}`, allow).text } : a)),
  };

  const unresolved = guarded.answers.filter((a) => a.needsUser).map((a) => a.question);
  const needsUserInput = [
    ...unresolved,
    ...(guarded.coverLetter.violations.some((v) => v.type === 'unverified_years' || v.type === 'unverified_seniority')
      ? ['Some generated statements about experience were withheld — please review the draft.']
      : []),
  ];

  return {
    intro: guarded.intro.text,
    coverLetter: guarded.coverLetter.text,
    coverLetterSubject: `Application for ${job.title}${job.company ? ` — ${job.company}` : ''}`,
    tailoredCv: { ...tailoredCv, summary: guarded.summary.text },
    answers: guarded.answers,
    salaryExpectation: profile.salaryExpectation || null,
    salaryCurrency: profile.salaryCurrency || settings.currency || null,
    noticePeriod: profile.noticePeriod || null,
    relevantSkills: tailoredCv.coreSkills,
    relevantProjects,
    relevantAchievements,
    needsUserInput: [...new Set(needsUserInput)],
    truthGuard: (() => {
      const violations = [...guarded.coverLetter.violations, ...guarded.intro.violations, ...guarded.summary.violations];
      return { ok: violations.length === 0, violations };
    })(),
    engine: llmAvailable(userId) ? 'llm+deterministic' : 'deterministic',
    generatedAt: new Date().toISOString(),
  };
}

/** Optional LLM polish. Called by the pipeline for higher-quality prose when configured. */
export async function polishCoverLetter({ draft, profile, job, truthIndex, userId = null }) {
  if (!llmAvailable(userId)) return draft;
  const text = await complete({
    userId,
    system:
      'You are an expert career writer. Rewrite the cover letter draft so it flows naturally and stays under 320 words. ' +
      'Use ONLY the facts in the draft and the candidate facts list. Never add employers, qualifications, certifications, ' +
      'tools, job titles, metrics or years of experience that are not present. Do not add placeholders.',
    prompt: `CANDIDATE FACTS (do not exceed):\n${JSON.stringify(
      {
        name: truthIndex.name,
        titles: truthIndex.titles,
        companies: truthIndex.companies,
        skills: truthIndex.skillLabels,
        years: truthIndex.yearsExperience,
        seniority: truthIndex.seniority,
        education: truthIndex.education,
        certifications: truthIndex.certifications,
        achievements: truthIndex.achievements?.slice(0, 6),
      },
      null,
      1
    )}\n\nJOB: ${job.title} at ${job.company}\n\nDRAFT:\n${draft}\n\nReturn only the rewritten letter.`,
    maxTokens: 700,
  });
  if (!text) return draft;
  const check = validate(text, truthIndex, { allow: [job?.company, job?.title].filter(Boolean) });
  if (!check.ok) {
    log.warn('LLM polish rejected by truth guard — keeping deterministic draft', {
      violations: check.violations.map((v) => v.type),
    });
    return draft;
  }
  return text.trim();
}

